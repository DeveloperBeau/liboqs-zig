    _ = @import("kem.zig");
    _ = @import("sig.zig");
    _ = @import("sig_stfl.zig");
    _ = @import("sig_stfl_secret_key.zig");
    _ = @import("keys.zig");
    _ = @import("typed.zig");
    _ = algorithms;
}
