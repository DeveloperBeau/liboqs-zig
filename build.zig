const std = @import("std");
const manifest = @import("build/manifest.zig");

// Single source of truth for which liboqs families are compiled and exposed.
// The same list scopes include/oqs/oqsconfig.h via tools/gen-manifest.sh.
// @embedFile (not a configure-time read) so editing the txt forces a rebuild.
const enabled_families = parseFamilies(@embedFile("build/enabled-families.txt"));

/// Parse the enabled-families manifest at comptime: one family per line,
/// trimmed, skipping blank lines and `#` comments.
fn parseFamilies(comptime raw: []const u8) []const []const u8 {
    @setEvalBranchQuota(10000);
    comptime {
        var families: []const []const u8 = &.{};
        var it = std.mem.tokenizeScalar(u8, raw, '\n');
        while (it.next()) |line| {
            const trimmed = std.mem.trim(u8, line, " \t\r");
            if (trimmed.len == 0 or trimmed[0] == '#') continue;
            families = families ++ .{trimmed};
        }
        return families;
    }
}

/// Look up a family's kind ("kem"/"sig"/"sig_stfl") from the manifest. Panics if the
/// family has no manifest entry (i.e. enabled-families.txt names something the
/// generator does not know about).
fn familyKind(comptime family: []const u8) []const u8 {
    comptime {
        @setEvalBranchQuota(10000);
        for (manifest.algorithms) |entry| {
            if (std.mem.eql(u8, entry.family, family)) {
                return switch (entry.kind) {
                    .kem => "kem",
                    .sig => "sig",
                    .sig_stfl => "sig_stfl",
                };
            }
        }
        @compileError("enabled-families.txt names '" ++ family ++ "' which has no entry in build/manifest.zig");
    }
}

/// The compiled liboqs static library and the assembled `oqs/` include directory.
const Cliboqs = struct {
    lib: *std.Build.Step.Compile,
    include: std.Build.LazyPath,
};

/// Builds cliboqs (the portable-only slice of liboqs) at the given optimize mode.
/// The stateful parity harnesses call this a second time at ReleaseFast.
fn buildCliboqs(b: *std.Build, target: std.Build.ResolvedTarget, optimize: std.builtin.Optimize) Cliboqs {
    // ------------------------------------------------------------------
    // Static C library: cliboqs (portable-only slice of liboqs 0.16.0).
    // ------------------------------------------------------------------
    const cliboqs_mod = b.createModule(.{
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });

    const cliboqs = b.addLibrary(.{
        .name = "cliboqs",
        .linkage = .static,
        .root_module = cliboqs_mod,
    });

    // liboqs C source comes from a hash-pinned dependency (build.zig.zon),
    // fetched by `zig fetch`. The tarball unpacks to a tree whose source
    // root is `src/` (same relative layout as the old vendored slice).
    const liboqs = b.dependency("liboqs", .{});

    // Root for all relative C source paths below.
    const vendor_src = liboqs.path("src");

    // Assemble the public `oqs/` umbrella include directory at build time:
    // copy each required upstream header to `oqs/<basename>`, plus our
    // in-repo (generated by tools/gen-manifest.sh) oqsconfig.h. The result is a generated
    // LazyPath consumed as an include dir by every group below.
    const hdrs = b.addWriteFiles();
    _ = hdrs.addCopyFile(b.path("include/oqs/oqsconfig.h"), "oqs/oqsconfig.h");
    const umbrella_headers = [_]struct { []const u8, []const u8 }{
        .{ "src/oqs.h", "oqs/oqs.h" },
        .{ "src/common/common.h", "oqs/common.h" },
        .{ "src/common/rand/rand.h", "oqs/rand.h" },
        .{ "src/common/rand/rand_nist.h", "oqs/rand_nist.h" },
        .{ "src/common/aes/aes_ops.h", "oqs/aes_ops.h" },
        .{ "src/common/aes/aes.h", "oqs/aes.h" },
        .{ "src/common/sha2/sha2_ops.h", "oqs/sha2_ops.h" },
        .{ "src/common/sha2/sha2.h", "oqs/sha2.h" },
        .{ "src/common/sha3/sha3_ops.h", "oqs/sha3_ops.h" },
        .{ "src/common/sha3/sha3.h", "oqs/sha3.h" },
        .{ "src/common/sha3/sha3x4_ops.h", "oqs/sha3x4_ops.h" },
        .{ "src/common/sha3/sha3x4.h", "oqs/sha3x4.h" },
        .{ "src/kem/kem.h", "oqs/kem.h" },
        .{ "src/sig/sig.h", "oqs/sig.h" },
        .{ "src/sig_stfl/sig_stfl.h", "oqs/sig_stfl.h" },
        .{ "src/sig_stfl/xmss/sig_stfl_xmss.h", "oqs/sig_stfl_xmss.h" },
        .{ "src/sig_stfl/lms/sig_stfl_lms.h", "oqs/sig_stfl_lms.h" },
    };
    for (umbrella_headers) |h| {
        _ = hdrs.addCopyFile(liboqs.path(h[0]), h[1]);
    }

    // Per-family umbrella headers, derived from enabled_families. Each family's
    // umbrella is oqs/<kind>_<family>.h (kem_<f>.h for KEMs, sig_<f>.h for SIGs);
    // its kind comes from the manifest. kem.h/sig.h #include these under the
    // family-level OQS_ENABLE_* guards, so the enabled set must match oqsconfig.h.
    // Stateful families are skipped here: sig_stfl.c includes their umbrella
    // headers unconditionally, so they are in the fixed list above.
    inline for (enabled_families) |fam| {
        const sub = comptime familyKind(fam); // "kem", "sig" or "sig_stfl"
        if (comptime std.mem.eql(u8, sub, "sig_stfl")) continue;
        const rel = b.fmt("src/{s}/{s}/{s}_{s}.h", .{ sub, fam, sub, fam });
        const dst = b.fmt("oqs/{s}_{s}.h", .{ sub, fam });
        _ = hdrs.addCopyFile(liboqs.path(rel), dst);
    }
    const oqs_include = hdrs.getDirectory();

    // Library-global include paths (order matters: pqclean_shims must
    // resolve before the internal sha2/sha3 headers). The assembled
    // umbrella dir replaces the old vendored `include/`.
    cliboqs_mod.addIncludePath(oqs_include);
    const include_dirs = [_][]const u8{
        "src",
        "src/common",
        "src/common/pqclean_shims",
        "src/common/aes",
        "src/common/sha2",
        "src/common/sha3",
        "src/common/sha3/xkcp_low/KeccakP-1600/plain-64bits",
        "src/common/sha3/xkcp_low/KeccakP-1600times4/serial",
        "src/common/rand",
    };
    for (include_dirs) |dir| {
        cliboqs_mod.addIncludePath(liboqs.path(dir));
    }

    // Base flags applied to every cliboqs C group.
    const base_flags = [_][]const u8{
        "-std=c11",
        "-DOQS_DIST_BUILD=1",
        // Disable UBSan for the vendored liboqs C entirely. Several PQClean
        // impls do benign UB on supported targets (unaligned u8[]->u64* casts in
        // GF arithmetic; SLH-DSA's SHA2 trips a different check on x86 Debug than
        // on arm64). Upstream compiles this C without sanitizers; trapping here
        // just aborts otherwise-correct code, and it varies by target/host.
        "-fno-sanitize=undefined",
        // POSIX/GNU extensions liboqs relies on (posix_memalign, strdup, ...).
        // Under -std=c11 (strict ISO) glibc hides these without a feature-test
        // macro, so Linux fails with implicit-declaration errors; Darwin headers
        // expose them regardless. liboqs' own CMake defines _GNU_SOURCE too.
        "-D_GNU_SOURCE",
    };

    // --- common (portable, OpenSSL OFF) + dispatchers -----------------
    cliboqs_mod.addCSourceFiles(.{
        .root = vendor_src,
        .flags = &base_flags,
        .files = &.{
            // common: aes
            "common/aes/aes_impl.c",
            "common/aes/aes_c.c",
            "common/aes/aes.c",
            // common: sha2
            "common/sha2/sha2_impl.c",
            "common/sha2/sha2_c.c",
            "common/sha2/sha2.c",
            // common: sha3
            "common/sha3/xkcp_sha3.c",
            "common/sha3/xkcp_sha3x4.c",
            "common/sha3/sha3.c",
            "common/sha3/sha3x4.c",
            // common: Keccak low-level (portable)
            "common/sha3/xkcp_low/KeccakP-1600/plain-64bits/KeccakP-1600-opt64.c",
            "common/sha3/xkcp_low/KeccakP-1600times4/serial/KeccakP-1600-times4-on1.c",
            // common: misc
            "common/common.c",
            "common/pqclean_shims/fips202.c",
            "common/pqclean_shims/fips202x4.c",
            "common/rand/rand.c",
            "common/rand/rand_nist.c",
            // dispatchers
            "kem/kem.c",
            "sig/sig.c",
            "sig_stfl/sig_stfl.c",
        },
    });

    // --- per-algorithm groups, driven by build/manifest.zig -----------
    // Each manifest entry whose family is enabled becomes one
    // addCSourceFiles group. Families come online incrementally via this
    // enable list. Enabling a family compiles ALL its variants (this is how
    // upstream builds; PQClean/mlkem-native namespace per-variant so there
    // are no symbol clashes).
    const is_macos = target.result.os.tag == .macos;

    for (manifest.algorithms) |entry| {
        var enabled = false;
        for (enabled_families) |fam| {
            if (std.mem.eql(u8, fam, entry.family)) {
                enabled = true;
                break;
            }
        }
        if (!enabled) continue;

        // Build a fresh flag slice per entry on the build arena.
        var flags: std.ArrayList([]const u8) = .empty;
        flags.appendSlice(b.allocator, &base_flags) catch @panic("OOM");
        for (entry.flags) |flag| {
            if (flag.macos_only and !is_macos) continue;
            // "-include <file>" flags carry a path relative to liboqs src/;
            // resolve it so clang (and Zig's cache hashing) can find the file.
            if (std.mem.startsWith(u8, flag.text, "-include ")) {
                const rel = flag.text["-include ".len..];
                flags.append(b.allocator, "-include") catch @panic("OOM");
                const abs = liboqs.builder.root.joinString(b.allocator, b.fmt("src/{s}", .{rel})) catch @panic("OOM");
                flags.append(b.allocator, abs) catch @panic("OOM");
                continue;
            }
            flags.append(b.allocator, flag.text) catch @panic("OOM");
        }
        for (entry.includes) |inc| {
            const abs = liboqs.builder.root.joinString(b.allocator, b.fmt("src/{s}", .{inc})) catch @panic("OOM");
            flags.append(b.allocator, b.fmt("-I{s}", .{abs})) catch @panic("OOM");
        }

        cliboqs_mod.addCSourceFiles(.{
            .root = vendor_src,
            .flags = flags.toOwnedSlice(b.allocator) catch @panic("OOM"),
            .files = entry.files,
        });
    }

    return .{ .lib = cliboqs, .include = oqs_include };
}

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    const clib = buildCliboqs(b, target, optimize);
    const cliboqs = clib.lib;
    const oqs_include = clib.include;
    b.installArtifact(cliboqs);

    // ------------------------------------------------------------------
    // Zig module `oqs` + test step.
    // ------------------------------------------------------------------
    const oqs_mod = b.addModule("oqs", .{
        .root_source_file = b.path("src/root.zig"),
        .target = target,
        .optimize = optimize,
    });
    oqs_mod.linkLibrary(cliboqs);
    oqs_mod.addIncludePath(oqs_include);

    // The build system's translate-c step turns the liboqs C API in src/c.h
    // into a Zig module. src/c.zig imports it as `c_api`.
    const translate_c = b.addTranslateC(.{
        .root_source_file = b.path("src/c.h"),
        .target = target,
        .optimize = optimize,
    });
    translate_c.addIncludePath(oqs_include);
    const c_api_mod = translate_c.createModule();
    oqs_mod.addImport("c_api", c_api_mod);

    const mod_tests = b.addTest(.{ .root_module = oqs_mod });
    const run_mod_tests = b.addRunArtifact(mod_tests);

    const test_step = b.step("test", "Run all tests");
    test_step.dependOn(&run_mod_tests.step);

    // Smoke test: instantiate + round-trip across the enabled families.
    const smoke_mod = b.createModule(.{
        .root_source_file = b.path("tests/smoke.zig"),
        .target = target,
        .optimize = optimize,
    });
    smoke_mod.addImport("oqs", oqs_mod);
    const smoke_tests = b.addTest(.{ .root_module = smoke_mod });
    const run_smoke_tests = b.addRunArtifact(smoke_tests);
    test_step.dependOn(&run_smoke_tests.step);

    // Seed for the fuzz tests, shared by every module that has one.
    const fuzz_seed = b.option(u64, "fuzz-seed", "Seed for the fuzz tests") orelse 0x5717_F022;

    // Typed-API tests: registry gate + namespace round-trips + type safety.
    const typed_mod = b.createModule(.{
        .root_source_file = b.path("tests/typed.zig"),
        .target = target,
        .optimize = optimize,
    });
    typed_mod.addImport("oqs", oqs_mod);
    // The typed stateful fuzz test takes the same seed as the core one.
    const typed_options = b.addOptions();
    typed_options.addOption(u64, "fuzz_seed", fuzz_seed);
    typed_mod.addOptions("build_options", typed_options);
    const typed_tests = b.addTest(.{ .root_module = typed_mod });
    const run_typed_tests = b.addRunArtifact(typed_tests);
    run_typed_tests.setName(b.fmt("run typed tests (fuzz seed 0x{x})", .{fuzz_seed}));
    test_step.dependOn(&run_typed_tests.step);

    // Registry tests: name lists, enabled checks, lookup and the lookup fuzz.
    const registry_mod = b.createModule(.{
        .root_source_file = b.path("tests/registry.zig"),
        .target = target,
        .optimize = optimize,
    });
    registry_mod.addImport("oqs", oqs_mod);
    const registry_options = b.addOptions();
    registry_options.addOption(u64, "fuzz_seed", fuzz_seed);
    registry_mod.addOptions("build_options", registry_options);
    const registry_tests = b.addTest(.{ .root_module = registry_mod });
    const run_registry_tests = b.addRunArtifact(registry_tests);
    run_registry_tests.setName(b.fmt("run registry tests (fuzz seed 0x{x})", .{fuzz_seed}));
    test_step.dependOn(&run_registry_tests.step);

    // Secret-zeroing test, also run at ReleaseFast. The main test run builds
    // keys.zig in the chosen mode, Debug by default. This run checks the wipe
    // where the optimizer is free to drop stores to memory that is about to
    // be freed. keys.zig only imports std, so this needs no cliboqs linkage.
    const keys_release_mod = b.createModule(.{
        .root_source_file = b.path("src/keys.zig"),
        .target = target,
        .optimize = .fast,
    });
    const keys_release_tests = b.addTest(.{ .root_module = keys_release_mod });
    const run_keys_release_tests = b.addRunArtifact(keys_release_tests);
    test_step.dependOn(&run_keys_release_tests.step);

    // Functional behavior tests (system RNG; never seeds KAT).
    const functional_mod = b.createModule(.{
        .root_source_file = b.path("tests/functional.zig"),
        .target = target,
        .optimize = optimize,
    });
    functional_mod.addImport("oqs", oqs_mod);
    const functional_tests = b.addTest(.{ .root_module = functional_mod });
    const run_functional_tests = b.addRunArtifact(functional_tests);
    test_step.dependOn(&run_functional_tests.step);

    // Concurrency tests (system RNG; own binary so no KAT DRBG leaks in).
    const concurrency_mod = b.createModule(.{
        .root_source_file = b.path("tests/concurrency.zig"),
        .target = target,
        .optimize = optimize,
    });
    concurrency_mod.addImport("oqs", oqs_mod);
    const concurrency_tests = b.addTest(.{ .root_module = concurrency_mod });
    const run_concurrency_tests = b.addRunArtifact(concurrency_tests);
    test_step.dependOn(&run_concurrency_tests.step);

    // Stateful signature tests (system RNG, never seeds KAT).
    const sig_stfl_mod = b.createModule(.{
        .root_source_file = b.path("tests/sig_stfl.zig"),
        .target = target,
        .optimize = optimize,
    });
    sig_stfl_mod.addImport("oqs", oqs_mod);
    // The fuzz test's seed comes from here, and the run step carries it in its
    // name, so `zig build test --summary all` shows it on a passing run. A test
    // that writes to stderr is reported as a failed command, so the test
    // itself prints the seed only when it fails.
    const sig_stfl_options = b.addOptions();
    sig_stfl_options.addOption(u64, "fuzz_seed", fuzz_seed);
    sig_stfl_mod.addOptions("build_options", sig_stfl_options);
    const sig_stfl_tests = b.addTest(.{ .root_module = sig_stfl_mod });
    const run_sig_stfl_tests = b.addRunArtifact(sig_stfl_tests);
    run_sig_stfl_tests.setName(b.fmt("run sig_stfl tests (fuzz seed 0x{x})", .{fuzz_seed}));
    test_step.dependOn(&run_sig_stfl_tests.step);

    // Stateful parity tests. They seed the KAT RNG, so they get their own
    // binary. The raw C API comes in as `c_api` so the tests can compare the
    // typed wrappers against the C reference. The height filter is the same
    // module the harnesses use.
    const stfl_filter_mod = b.createModule(.{
        .root_source_file = b.path("harness/stfl_filter.zig"),
        .target = target,
        .optimize = optimize,
    });
    const stfl_compare_mod = b.createModule(.{
        .root_source_file = b.path("harness/stfl_compare.zig"),
        .target = target,
        .optimize = optimize,
    });
    stfl_compare_mod.addImport("stfl_filter", stfl_filter_mod);
    const stfl_parity_mod = b.createModule(.{
        .root_source_file = b.path("tests/stfl_parity.zig"),
        .target = target,
        .optimize = optimize,
    });
    stfl_parity_mod.addImport("oqs", oqs_mod);
    stfl_parity_mod.addImport("c_api", c_api_mod);
    stfl_parity_mod.addImport("stfl_filter", stfl_filter_mod);
    stfl_parity_mod.addImport("stfl_compare", stfl_compare_mod);
    const stfl_parity_options = b.addOptions();
    stfl_parity_options.addOption(u64, "fuzz_seed", fuzz_seed);
    stfl_parity_mod.addOptions("build_options", stfl_parity_options);
    const stfl_parity_tests = b.addTest(.{ .root_module = stfl_parity_mod });
    const run_stfl_parity_tests = b.addRunArtifact(stfl_parity_tests);
    run_stfl_parity_tests.setName(b.fmt("run stfl_parity tests (fuzz seed 0x{x})", .{fuzz_seed}));
    // Reads the frozen snapshot from the repo root.
    run_stfl_parity_tests.setCwd(b.path("."));
    test_step.dependOn(&run_stfl_parity_tests.step);

    // Context string tests for the core and typed signatures. They seed the
    // KAT RNG to compare with the raw C API, so they get their own binary.
    const sig_context_mod = b.createModule(.{
        .root_source_file = b.path("tests/sig_context.zig"),
        .target = target,
        .optimize = optimize,
    });
    sig_context_mod.addImport("oqs", oqs_mod);
    sig_context_mod.addImport("c_api", c_api_mod);
    const sig_context_options = b.addOptions();
    sig_context_options.addOption(u64, "fuzz_seed", fuzz_seed);
    sig_context_mod.addOptions("build_options", sig_context_options);
    const sig_context_tests = b.addTest(.{ .root_module = sig_context_mod });
    const run_sig_context_tests = b.addRunArtifact(sig_context_tests);
    run_sig_context_tests.setName(b.fmt("run sig_context tests (fuzz seed 0x{x})", .{fuzz_seed}));
    test_step.dependOn(&run_sig_context_tests.step);

    // ------------------------------------------------------------------
    // C reference harness: cref
    // ------------------------------------------------------------------
    const cref_mod = b.createModule(.{
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    const cref = b.addExecutable(.{
        .name = "cref",
        .root_module = cref_mod,
    });
    cref_mod.addCSourceFile(.{ .file = b.path("harness/cref.c"), .flags = &.{"-std=c11"} });
    cref_mod.addIncludePath(oqs_include);
    cref_mod.linkLibrary(cliboqs);
    b.installArtifact(cref);

    // ------------------------------------------------------------------
    // Zig wrapper harness: zref
    // ------------------------------------------------------------------
    const zref_mod = b.createModule(.{
        .root_source_file = b.path("harness/zref.zig"),
        .target = target,
        .optimize = optimize,
    });
    zref_mod.addImport("oqs", oqs_mod);
    const zref = b.addExecutable(.{
        .name = "zref",
        .root_module = zref_mod,
    });
    b.installArtifact(zref);

    // ------------------------------------------------------------------
    // Stateful parity harnesses: stfl_cref (raw C) and stfl_zref (typed
    // wrappers). They are separate from cref and zref so the frozen snapshot
    // has no stateful lines. Always ReleaseFast, whatever -Doptimize says,
    // because height 16 keygen in Debug can take hours.
    // ------------------------------------------------------------------
    const stfl_clib = if (optimize == .fast) clib else buildCliboqs(b, target, .fast);
    const stfl_oqs_mod = b.createModule(.{
        .root_source_file = b.path("src/root.zig"),
        .target = target,
        .optimize = .fast,
    });
    stfl_oqs_mod.linkLibrary(stfl_clib.lib);
    stfl_oqs_mod.addIncludePath(stfl_clib.include);
    const stfl_translate_c = b.addTranslateC(.{
        .root_source_file = b.path("src/c.h"),
        .target = target,
        .optimize = .fast,
    });
    stfl_translate_c.addIncludePath(stfl_clib.include);
    stfl_oqs_mod.addImport("c_api", stfl_translate_c.createModule());

    const stfl_cref_mod = b.createModule(.{
        .target = target,
        .optimize = .fast,
        .link_libc = true,
    });
    stfl_cref_mod.addCSourceFile(.{ .file = b.path("harness/stfl_cref.c"), .flags = &.{"-std=c11"} });
    stfl_cref_mod.addIncludePath(stfl_clib.include);
    stfl_cref_mod.linkLibrary(stfl_clib.lib);
    const stfl_cref = b.addExecutable(.{ .name = "stfl_cref", .root_module = stfl_cref_mod });
    b.installArtifact(stfl_cref);

    const stfl_harness_filter_mod = b.createModule(.{
        .root_source_file = b.path("harness/stfl_filter.zig"),
        .target = target,
        .optimize = .fast,
    });
    const stfl_zref_mod = b.createModule(.{
        .root_source_file = b.path("harness/stfl_zref.zig"),
        .target = target,
        .optimize = .fast,
    });
    stfl_zref_mod.addImport("oqs", stfl_oqs_mod);
    stfl_zref_mod.addImport("stfl_filter", stfl_harness_filter_mod);
    const stfl_zref = b.addExecutable(.{ .name = "stfl_zref", .root_module = stfl_zref_mod });
    b.installArtifact(stfl_zref);

    const stfl_compare_exe_mod = b.createModule(.{
        .root_source_file = b.path("harness/stfl_compare.zig"),
        .target = target,
        .optimize = .fast,
    });
    stfl_compare_exe_mod.addImport("stfl_filter", stfl_harness_filter_mod);
    const stfl_compare_exe = b.addExecutable(.{ .name = "stfl_compare", .root_module = stfl_compare_exe_mod });
    b.installArtifact(stfl_compare_exe);

    // ------------------------------------------------------------------
    // Parity gate: full-coverage byte-identical diff of cref vs zref.
    // Script-driven (addSystemCommand) so the sharded harnesses stream
    // per-algorithm progress live. A Zig test would buffer it, and a
    // multi-minute run would look hung. See tools/parity.sh.
    // ------------------------------------------------------------------
    const run_parity = b.addSystemCommand(&.{ "bash", "tools/parity.sh" });
    run_parity.step.dependOn(b.getInstallStep());
    run_parity.has_side_effects = true; // always re-run; not cacheable
    const parity_step = b.step("parity", "Full byte-identical parity: C reference vs Zig wrapper");
    parity_step.dependOn(&run_parity.step);

    // The stateful check runs after the 262-algorithm compare. It sits outside
    // the frozen snapshot. See tools/stateful-parity.sh.
    const run_stfl_parity = b.addSystemCommand(&.{ "bash", "tools/stateful-parity.sh" });
    run_stfl_parity.step.dependOn(b.getInstallStep());
    run_stfl_parity.step.dependOn(&run_parity.step);
    run_stfl_parity.has_side_effects = true;
    parity_step.dependOn(&run_stfl_parity.step);

    // ------------------------------------------------------------------
    // Snapshot gate: zref output vs frozen liboqs reference digests.
    // ------------------------------------------------------------------
    const run_snapshot = b.addSystemCommand(&.{ "bash", "tools/snapshot.sh" });
    run_snapshot.step.dependOn(b.getInstallStep());
    run_snapshot.has_side_effects = true;
    const snapshot_step = b.step("snapshot", "Check zref against the frozen liboqs reference snapshot");
    snapshot_step.dependOn(&run_snapshot.step);
}
